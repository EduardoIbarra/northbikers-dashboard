alter table public.news
    add column if not exists status text not null default 'draft',
    add column if not exists published_at timestamptz,
    add column if not exists author_id uuid references auth.users(id) on delete set null,
    add column if not exists cover_image_url text,
    add column if not exists image_metadata jsonb not null default '[]'::jsonb,
    add column if not exists likes_count bigint not null default 0,
    add column if not exists shares_count bigint not null default 0,
    add column if not exists comments_count bigint not null default 0;

alter table public.news drop constraint if exists news_status_check;
alter table public.news add constraint news_status_check check (status in ('draft', 'published', 'archived'));

-- Keep existing news available to clients that already consume the table.
update public.news
set status = 'published',
    published_at = coalesce(published_at, created_at, now())
where published_at is null;

create table if not exists public.news_likes (
    id bigint generated by default as identity primary key,
    news_id bigint not null references public.news(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (news_id, user_id)
);

create table if not exists public.news_comments (
    id bigint generated by default as identity primary key,
    news_id bigint not null references public.news(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    author_name text not null,
    body text not null check (char_length(body) between 1 and 4000),
    status text not null default 'visible' check (status in ('visible', 'hidden')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.news_shares (
    id bigint generated by default as identity primary key,
    news_id bigint not null references public.news(id) on delete cascade,
    user_id uuid references auth.users(id) on delete set null,
    platform text not null default 'native' check (platform in ('native', 'whatsapp', 'facebook', 'instagram', 'copy_link', 'other')),
    created_at timestamptz not null default now()
);

create index if not exists news_published_feed_idx on public.news (published_at desc, id desc) where status = 'published';
create index if not exists news_likes_news_id_idx on public.news_likes (news_id);
create index if not exists news_comments_feed_idx on public.news_comments (news_id, created_at desc) where status = 'visible';
create index if not exists news_shares_news_id_idx on public.news_shares (news_id);

