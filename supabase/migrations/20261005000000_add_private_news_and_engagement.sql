create or replace function public.refresh_news_engagement_counts()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if tg_table_name = 'news_likes' then
        if tg_op = 'INSERT' then
            update public.news set likes_count = likes_count + 1 where id = new.news_id;
            return new;
        elsif tg_op = 'DELETE' then
            update public.news set likes_count = greatest(likes_count - 1, 0) where id = old.news_id;
            return old;
        end if;
    elsif tg_table_name = 'news_shares' then
        if tg_op = 'INSERT' then
            update public.news set shares_count = shares_count + 1 where id = new.news_id;
            return new;
        end if;
    elsif tg_table_name = 'news_comments' then
        if tg_op = 'INSERT' then
            update public.news set comments_count = comments_count + 1 where id = new.news_id;
            return new;
        elsif tg_op = 'DELETE' then
            update public.news set comments_count = greatest(comments_count - 1, 0) where id = old.news_id;
            return old;
        end if;
    end if;
    return null;
end;
$$;

drop trigger if exists news_likes_count_trigger on public.news_likes;
create trigger news_likes_count_trigger after insert or delete on public.news_likes
for each row execute function public.refresh_news_engagement_counts();
drop trigger if exists news_shares_count_trigger on public.news_shares;
create trigger news_shares_count_trigger after insert on public.news_shares
for each row execute function public.refresh_news_engagement_counts();
